// Regenerates src/data/safetyImageManifest.ts from actual files in public/images/safety/.
// Run: node scripts/gen-safety-manifest.cjs
const { readdirSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");

const dir = join(__dirname, "..", "public", "images", "safety");
const files = readdirSync(dir).filter((f) => /\.(jpg|jpeg|png|webp|svg)$/i.test(f)).sort();

const byId = {};
for (const f of files) {
  const m = f.match(/^(.+)-([123])\.(.+)$/);
  if (!m) { console.warn("skip (bad name):", f); continue; }
  const [, id, v] = m;
  (byId[id] = byId[id] || {})[v] = f;
}

const ids = Object.keys(byId).sort();
let missing = 0;
for (const id of ids) {
  for (const v of ["1", "2", "3"]) {
    if (!byId[id][v]) { console.warn("MISSING variant:", id, v); missing++; }
  }
}

const out = `// AUTO-GENERATED by scripts/gen-safety-manifest.cjs — do not edit by hand.
export const SAFETY_IMAGE_FILES: Record<string, string[]> = ${JSON.stringify(
  Object.fromEntries(ids.map((id) => [id, ["1", "2", "3"].map((v) => byId[id][v]).filter(Boolean)])),
  null,
  2,
)};
`;
writeFileSync(join(__dirname, "..", "src", "data", "safetyImageManifest.ts"), out);
console.log(`ids: ${ids.length}, files: ${files.length}, missing variants: ${missing}`);
